'use strict';
// Retained because later pipeline wiring can accidentally key successful work
// to unrelated attempts or turn unknown execution into reusable success.
const assert = require('node:assert/strict');
const fs = require('node:fs');
const path = require('node:path');
const {openPipelineState} = require('./pipeline-state.cjs');
function check(root) {
  if (!root || !path.isAbsolute(root)) throw Error('Supply a fresh absolute fixture root under its test owner.');
  fs.mkdirSync(root);
  const file = path.join(root, 'pipeline.json');
  const output = path.join(root, 'engine.bin');
  const identity = {project: root, platform: 'fixture', work: 'fixed-source'};
  const decisionsPath = path.join(root, 'reuse-decisions.json');
  const open = (resume, reuseDecisionsPath) => openPipelineState({file, identity, resume, lockHeld: true, reuseDecisionsPath});
  let pipeline = open(false);
  const executions = {source: 0, build: 0, prepare: 0};
  function run(name, dependencies, fail = false) {
    const inputs = {selected: name};
    if (pipeline.lookup(name, {inputs, dependencies})) return;
    pipeline.start(name, {inputs, dependencies}); executions[name]++;
    if (name === 'build') fs.writeFileSync(output, 'verified engine');
    pipeline.finish(name, {exitCode: fail ? 17 : 0, outputs: name === 'build' ? [output] : []});
  }
  run('source', []); run('build', ['source']); run('prepare', ['build'], true);
  pipeline = open(true);
  run('source', []); run('build', ['source']); run('prepare', ['build']);
  assert.deepEqual(executions, {source: 1, build: 1, prepare: 2});
  assert.equal(pipeline.snapshot.stages.prepare[0].exitCode, 17);
  const original = pipeline.snapshot.stages.build[0];
  const changedInputs = {selected: 'build', environment: 'changed'};
  function needsReview(operation) {
    let review;
    assert.throws(operation, error => { review = error.review; return error.code === 'VERIFICATION_REVIEW_REQUIRED'; });
    return review;
  }
  const review = needsReview(() => pipeline.lookup('build', {inputs: changedInputs, dependencies: ['source']}));
  const requestPath = path.join(root, 'review-request.json');
  fs.writeFileSync(requestPath, JSON.stringify({file, identity, resume: true, lockHeld: true, action: 'lookup', name: 'build', options: {inputs: changedInputs, dependencies: ['source']}}));
  const cli = require('node:child_process').spawnSync(process.execPath, [path.join(__dirname, 'pipeline-state.cjs'), requestPath], {encoding: 'utf8'});
  assert.equal(cli.status, 3);
  const report = JSON.parse(cli.stderr);
  assert.equal(report.status, 'review-required');
  assert.equal(report.review.reviewId, review.reviewId);
  const decision = {scope: review.scope, reviewId: review.reviewId, action: 'reuse', reason: 'Reviewed environment does not affect this output.'};
  const choose = choice => {
    fs.writeFileSync(decisionsPath, JSON.stringify({schema: 1, decisions: [choice]}));
    pipeline = open(true, decisionsPath);
  };
  assert.throws(() => choose({...decision, reason: ' '}), /nonblank reason/);
  choose({...decision, reviewId: '0'.repeat(64)});
  needsReview(() => pipeline.lookup('build', {inputs: changedInputs, dependencies: ['source']}));
  choose({...decision, action: 'rerun'});
  assert.equal(pipeline.lookup('build', {inputs: changedInputs, dependencies: ['source']}), null);
  assert.deepEqual(pipeline.snapshot.stages.build[0], original);
  choose(decision);
  const reused = pipeline.lookup('build', {inputs: changedInputs, dependencies: ['source']});
  assert.equal(reused.id, original.id);
  assert.equal(reused.inputsKey, original.inputsKey);
  assert.deepEqual(reused.outputs, original.outputs);
  assert.equal(reused.reuseReviews[0].decision.reason, decision.reason);
  assert.deepEqual(pipeline.lookup('build', {inputs: changedInputs, dependencies: ['source']}), reused);
  assert.equal(pipeline.snapshot.stages.build[0].reuseReviews.length, 1);
  assert.throws(() => pipeline.lookup('build', {inputs: changedInputs, dependencies: ['source'], outputs: [path.join(root, 'other.bin')]}), /output paths differ/);
  pipeline = open(true);
  pipeline.start('source', {inputs: {selected: 'source'}}); pipeline.finish('source', {exitCode: 0});
  needsReview(() => pipeline.lookup('build', {inputs: {selected: 'build'}, dependencies: ['source']}));
  pipeline.start('failed-dependency'); pipeline.finish('failed-dependency', {exitCode: 1});
  assert.equal(pipeline.lookup('failed-dependency'), null);
  assert.throws(() => pipeline.lookup('build', {inputs: changedInputs, dependencies: ['failed-dependency']}), /not successful/);
  choose(decision);
  fs.writeFileSync(output, 'changed engine');
  assert.throws(() => pipeline.lookup('build', {inputs: changedInputs, dependencies: ['source']}), /integrity changed/);
  fs.unlinkSync(output);
  assert.throws(() => pipeline.lookup('build', {inputs: changedInputs, dependencies: ['source']}), /ENOENT/);
  assert.throws(() => openPipelineState({file, identity: {...identity, work: 'changed-source'}, resume: true, lockHeld: true}), /identity changed/);
  assert.throws(() => openPipelineState({file, identity, resume: true}), /exclusive owner lease/);
  pipeline.start('live');
  assert.throws(() => pipeline.lookup('live'), /unresolved execution/);
  assert.throws(() => pipeline.start('live'), /unresolved execution/);
  pipeline.finish('live', {exitCode: null});
  assert.throws(() => pipeline.lookup('live'), /unresolved execution/);
  assert.throws(() => pipeline.start('live'), /unresolved execution/);
  const evidence = path.join(root, 'stopped.json');
  fs.writeFileSync(evidence, JSON.stringify({producer_stopped_verified: true, reason: 'Fixture controller observed its owned operation stop.'}));
  const digest = () => require('node:crypto').createHash('sha256').update(fs.readFileSync(evidence)).digest('hex');
  const recovery = name => ({expectedStageId: pipeline.snapshot.stages[name].at(-1).id, producer_stopped_verified: true,
    evidence_ref: evidence, evidence_sha256: digest(), reason: 'Owned operation stop verified by fixture controller.'});
  const liveRequest = recovery('live');
  assert.throws(() => pipeline.recover('live', {...liveRequest, producer_stopped_verified: false}), /verified producer stop/);
  assert.throws(() => pipeline.recover('live', {...liveRequest, expectedStageId: 'stale'}), /exact current/);
  assert.throws(() => pipeline.recover('live', {...liveRequest, reason: ' '}), /nonblank reason/);
  assert.throws(() => pipeline.recover('live', {...liveRequest, evidence_ref: 'relative.json'}), /absolute evidence/);
  assert.throws(() => pipeline.recover('live', {...liveRequest, evidence_sha256: '0'.repeat(64)}), /SHA-256/);
  assert.throws(() => pipeline.recover('live', {...liveRequest, evidence_ref: root}), /regular file/);
  for (const evidence_ref of [file, `${file}.update-lock`, `${file}.tmp`, output]) {
    assert.throws(() => pipeline.recover('live', {...liveRequest, evidence_ref}), /overlaps/);
  }
  const linked = path.join(root, 'linked-evidence');
  fs.symlinkSync(root, linked, process.platform === 'win32' ? 'junction' : 'dir');
  assert.throws(() => pipeline.recover('live', {...liveRequest, evidence_ref: path.join(linked, 'stopped.json')}), /linked/);
  if (process.platform === 'win32') fs.rmdirSync(linked); else fs.unlinkSync(linked);
  const hardlink = path.join(root, 'hardlinked-evidence.json');
  fs.linkSync(evidence, hardlink);
  assert.throws(() => pipeline.recover('live', liveRequest), /unlinked regular/);
  fs.unlinkSync(hardlink);
  const recoveredLive = pipeline.recover('live', liveRequest);
  assert.equal(recoveredLive.status, 'unknown'); assert.equal(recoveredLive.exitCode, null);
  assert.equal(recoveredLive.recovery.priorStatus, 'unknown');
  assert.deepEqual(pipeline.recover('live', liveRequest), recoveredLive);
  assert.throws(() => pipeline.recover('live', {...liveRequest, reason: 'Different recovery request.'}), /differs/);
  assert.equal(pipeline.lookup('live'), null);
  assert.throws(() => pipeline.start('dependent-on-unknown', {dependencies: ['live']}), /not successful/);
  fs.writeFileSync(evidence, 'tampered stop evidence');
  assert.throws(() => pipeline.start('live'), /SHA-256/);
  fs.writeFileSync(evidence, JSON.stringify({producer_stopped_verified: true, reason: 'Fixture controller observed its owned operation stop.'}));
  pipeline.start('live');
  assert.equal(pipeline.snapshot.stages.live.length, 2);
  assert.deepEqual(pipeline.snapshot.stages.live[0], recoveredLive);
  assert.throws(() => pipeline.recover('live', liveRequest), /exact current/);
  const runningRequest = recovery('live');
  assert.throws(() => pipeline.recover('live', {...runningRequest, producer_stopped_verified: undefined}), /verified producer stop/);
  const recoveredRunning = pipeline.recover('live', runningRequest);
  assert.equal(recoveredRunning.recovery.priorStatus, 'running');
  assert.equal(recoveredRunning.status, 'unknown'); assert.equal(recoveredRunning.exitCode, null);
  const changed = pipeline.snapshot;
  changed.stages.live.at(-1).inputsKey = 'changed stage';
  fs.writeFileSync(file, JSON.stringify(changed));
  assert.throws(() => pipeline.start('live'), /bound recovery receipt/);
  fs.writeFileSync(file, JSON.stringify({...changed, stages: {...changed.stages, live: [recoveredLive, recoveredRunning]}}));
  pipeline.start('live'); pipeline.finish('live', {exitCode: 0});
  assert.throws(() => pipeline.recover('live', recovery('live')), /exact current/);
  assert.throws(() => pipeline.recover('prepare', recovery('prepare')), /exact current/);
  pipeline.start('failed-recovery'); pipeline.finish('failed-recovery', {exitCode: 3});
  assert.throws(() => pipeline.recover('failed-recovery', recovery('failed-recovery')), /exact current/);
  pipeline.start('sync-failure');
  pipeline.finish('sync-failure', {exitCode: null, outcome: 'failed', error: 'Synchronous validation rejected input.'});
  pipeline.start('sync-failure');
  assert.throws(() => pipeline.finish('sync-failure', {exitCode: null, outcome: 'succeeded'}), /actual exit code zero/);
  pipeline.finish('sync-failure', {exitCode: 0});
  assert.equal(pipeline.snapshot.stages['sync-failure'][0].exitCode, null);
  const buildChild = open(true);
  pipeline.start('parent-observation');
  buildChild.start('build-child');
  pipeline.finish('parent-observation', {exitCode: 0});
  buildChild.finish('build-child', {exitCode: 0});
  assert.equal(pipeline.snapshot.stages['parent-observation'][0].exitCode, 0);
  assert.equal(pipeline.snapshot.stages['build-child'][0].exitCode, 0);
  // Later reader entry points must not bypass the atomic publisher's lock.
  const observationLock = `${file}.update-lock`;
  fs.writeFileSync(observationLock, 'occupied owner', {flag: 'wx'});
  try {
    assert.throws(() => pipeline.snapshot, /update lock is unavailable/);
    assert.throws(() => open(true), /update lock is unavailable/);
    assert.equal(fs.readFileSync(observationLock, 'utf8'), 'occupied owner');
  } finally { fs.unlinkSync(observationLock); }
  const intactState = fs.readFileSync(file, 'utf8');
  fs.writeFileSync(file, '{invalid');
  assert.throws(() => pipeline.snapshot, SyntaxError);
  assert.equal(fs.existsSync(observationLock), false);
  assert.throws(() => open(true), SyntaxError);
  assert.equal(fs.existsSync(observationLock), false);
  fs.unlinkSync(file);
  assert.throws(() => pipeline.snapshot, /ENOENT/);
  assert.equal(fs.existsSync(observationLock), false);
  assert.throws(() => open(true), /Resume requires/);
  fs.writeFileSync(file, intactState);
  fs.writeFileSync(`${file}.tmp`, 'unresolved prior atomic write', {flag: 'wx'});
  assert.throws(() => pipeline.start('stale-temp'), /EEXIST/);
  assert.equal(fs.readFileSync(`${file}.tmp`, 'utf8'), 'unresolved prior atomic write');
  assert.equal(pipeline.snapshot.stages['stale-temp'], undefined);
  console.log('pipeline state: source/build reuse, failed retry, output identity, lease assertion, running/unknown protection, synchronous failure passed');
}
if (require.main === module) check(process.argv[2]);
module.exports = {check};
